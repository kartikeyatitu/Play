"use client";
import { Button } from "@/components/ui/button";
import { Download } from "lucide-react";

export function DownloadReceipt({ studentName, month }: { studentName: string, month: string }) {
  return (
    <Button 
      size="sm" 
      variant="outline"
      onClick={() => {
        const printWindow = window.open('', '_blank');
        printWindow?.document.write(`
          <html>
            <head><title>Receipt - ${month}</title></head>
            <body style="font-family: sans-serif; padding: 40px; color: #111;">
              <h1 style="color: #3b82f6;">Official Academy Receipt</h1>
              <hr />
              <p><strong>Student:</strong> ${studentName}</p>
              <p><strong>Month:</strong> ${month}</p>
              <p><strong>Status:</strong> PAID IN FULL</p>
              <br />
              <p><em>Generated by Triq</em></p>
              <script>window.print(); window.onafterprint = function(){ window.close(); }</script>
            </body>
          </html>
        `);
        printWindow?.document.close();
      }}
      className="bg-zinc-800 text-zinc-300 border-zinc-700 hover:bg-zinc-700 h-7 text-xs"
    >
      <Download className="w-3 h-3 mr-1" /> Receipt
    </Button>
  );
}
